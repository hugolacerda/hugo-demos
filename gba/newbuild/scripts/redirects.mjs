// Writes public/_redirects, Netlify's redirect rules (map ticket 14). Runs
// before every dev and build (package.json), so the per-article rules follow
// src/content/index.json; the file is committed so a diff shows every change.
//
// Netlify reads the rules top to bottom and the first match wins. A rule whose
// source is an existing page never fires (rules are not forced), and the CDN
// normalises a trailing slash before matching, so `/about-us` also catches
// `/about-us/`. Trailing slashes on live pages (`/start-here/`, the 627
// legacy URLs in GBA-site-audits/2026-10-06/legacy_url_audit_2026-10-06.csv)
// need no rule: with Pretty URLs Netlify answers them with a 301 to the bare
// slug. tests/redirects.py checks all of it against a running site.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const index = JSON.parse(readFileSync(new URL('src/content/index.json', root), 'utf8'));

// [source, target, why]. Sources without a trailing slash; Netlify matches both forms.
const RULES = [
  // The listing runs to 52 pages, not the live 54 (ticket 11): the two offsets past the end.
  ['/news-and-events/624', '/news-and-events/612', 'live listing page 53'],
  ['/news-and-events/636', '/news-and-events/612', 'live listing page 54'],
  // Live 301s the rebuild keeps (VERIFICATION_2026-10-21.md, ticket 14's Question).
  ['/industries-we-service', '/industry-insider', 'duplicate page, 301 live'],
  ['/businesses-weve-sold', '/businesses-we-have-sold', 'duplicate page, 301 live'],
  ['/lshowcase-categories/home', '/', 'logo-showcase plugin page'],
  ['/site-map', '/sitemap', 'the /sitemap page links here'],
  // The six retired pages: Lorem Ipsum placeholders on Oct 6, 404 since Oct 21; each to its
  // closest live page (Hugo, 2026-10-25).
  ['/what-type-of-buyer-are-you', '/what-kind-of-buyers-are-you-most-likely-to-meet', 'retired placeholder'],
  ['/faqs', '/start-here', 'retired placeholder'],
  ['/financing', '/financing-business-purchase', 'retired placeholder'],
  ['/white-papers', '/news-and-events', 'retired placeholder'],
  ['/videos', '/news-and-events', 'retired placeholder'],
  ['/industry-terms', '/news-and-events', 'retired placeholder'],
  // The old WordPress site's URLs that still redirect live (legacy URL audit, Oct 6:
  // the 11 "3xx_real" rows, plus /team and the three /team/<name> bios, 301 to /our-team live).
  ['/about-us', '/our-team', 'old site'],
  ['/about-us/our-team', '/our-team', 'old site'],
  ['/about-us/affiliations', '/affiliations', 'old site'],
  ['/about-us/privacy-policy', '/privacy-policy', 'old site'],
  ['/broker-review/*', '/our-team', 'old site (/broker-review/jon-buehler)'],
  ['/team', '/our-team', 'old site'],
  ['/team/*', '/our-team', 'old site bios (/team/gary-hallett, /team/cal-heseman, /team/nancy-hallett)'],
  ['/blog', '/news-and-events', 'old site'],
  ['/blog/page/*', '/news-and-events', 'old site (/blog/page/4, /8, /10, /11)'],
  ['/valuation', '/assessing-your-options', 'old site'],
];

const lines = [
  '# Generated by scripts/redirects.mjs (map ticket 14); edit the script, not this file.',
  '# Netlify reads top to bottom, first match wins; anything unmatched that is not a page gets /404.html.',
  '',
];
const width = Math.max(...RULES.map(([s]) => s.length), 40);
for (const [source, target, why] of RULES) {
  lines.push(`# ${why}`, `${source.padEnd(width)}  ${target}  301`);
}
// Every article was also served at /news-and-events/<slug>; live 301s all of them (60 were
// linked, VERIFICATION_2026-10-21.md P1.4). One rule per article, so the listing's own pages
// (/news-and-events/12 ...) never meet a placeholder.
lines.push('', '# Every article at its old /news-and-events/<slug> address');
const articles = Object.entries(index).filter(([, v]) => v.kind === 'article').map(([, v]) => v.path).sort();
for (const path of articles) {
  lines.push(`/news-and-events${path}  ${path}  301`);
}
writeFileSync(new URL('public/_redirects', root), lines.join('\n') + '\n');
console.log(`_redirects: ${RULES.length} rules and ${articles.length} article rules`);
