// Writes dist/_headers, Netlify's response headers (map ticket 12). Runs after
// every build (package.json postbuild), because the Content-Security-Policy
// allows the site's inline scripts by hash and the hashes follow the build.
//
// What it fixes on Chuck's host (GBA-site-audits/2026-10-21/VERIFICATION_2026-10-21.md,
// "Confirmed unchanged"): a CSP Chrome rejects ('strict-dynamic' as a directive name,
// script-src * 'unsafe-inline' 'unsafe-eval', a report-uri on Chuck's dev host) and a
// Permissions-Policy that does not parse (a typographic quote where a comma belongs).
//
// The policy, source by source (scanned from dist/ on 2026-10-25):
//   scripts   the site's own bundles, plus its two inline scripts by hash (the mobile
//             menu Astro inlines, the readiness modal's); JSON-LD blocks are data and
//             need no allowance. No 'unsafe-inline', no 'unsafe-eval'.
//   styles    the site's own and Google Fonts' stylesheet; 'unsafe-inline' because the
//             live content carries inline style attributes on every page (ticket 11).
//   fonts     the site's own and Google Fonts' files (Poppins).
//   images    the site's own, and data: URIs (Bootstrap draws the modal close button
//             and the select arrows as data: SVGs); no outside image anywhere in dist/.
//   connect   the readiness modal posts its answers to a GoHighLevel webhook.
//   forms     post to the site itself (ticket 13 decides the endpoint).
// Ticket 13 extends it if the forms add a captcha (Cloudflare Turnstile is the lean).
//
// NOINDEX: every deploy before cutover is staging, so every response says noindex.
// Ticket 19 turns it off as part of the cutover.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const NOINDEX = true;
const dist = new URL('../dist/', import.meta.url).pathname;

function* htmlFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* htmlFiles(path);
    else if (entry.name.endsWith('.html')) yield path;
  }
}

// Inline <script> elements that execute: no src, and not a JSON-LD data block.
const hashes = new Set();
for (const file of htmlFiles(dist)) {
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/g)) {
    const attrs = m[1] ?? '';
    if (/\ssrc=/.test(attrs) || /type=["']?application\/ld\+json/.test(attrs) || !m[2]) continue;
    hashes.add(`'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'`);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(' ')}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  "img-src 'self' data:",
  "connect-src 'self' https://services.leadconnectorhq.com",
  "form-action 'self'",
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  'upgrade-insecure-requests',
].join('; ');

const headers = [
  `Content-Security-Policy: ${csp}`,
  'Referrer-Policy: strict-origin-when-cross-origin',
  'Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()',
  'X-Content-Type-Options: nosniff',
  'X-Frame-Options: DENY',
  ...(NOINDEX ? ['X-Robots-Tag: noindex'] : []),
];

writeFileSync(join(dist, '_headers'), `# Generated by scripts/headers.mjs after every build (map ticket 12).\n/*\n${headers.map((h) => `  ${h}`).join('\n')}\n`);
console.log(`_headers: ${hashes.size} inline script hashes, noindex ${NOINDEX ? 'on' : 'off'}`);
